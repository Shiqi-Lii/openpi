def test_pi05_legato_model():
    key = jax.random.key(0)
    config = pi0_config.Pi0Config(
        paligemma_variant="dummy",
        action_expert_variant="dummy",
        pi05=True,
        action_dim=8,
        action_horizon=6,
        max_token_len=16,
        legato_enabled=True,
        legato_omega_dim=7,
        legato_loss_action_dim=6,
        legato_train_num_steps=4,
        legato_full_guidance_steps=2,
        legato_ramp_steps=2,
    )
    model = config.create(key)

    batch_size = 2
    obs, act = config.fake_obs(batch_size), config.fake_act(batch_size)

    loss = nnx_utils.module_jit(model.compute_loss)(key, obs, act)
    assert loss.shape == (batch_size, config.action_horizon)

    free_actions = nnx_utils.module_jit(model.sample_actions)(key, obs, num_steps=4)
    assert free_actions.shape == (batch_size, model.action_horizon, model.action_dim)

    prev_actions = jax.random.normal(key, (batch_size, config.action_horizon, config.action_dim))
    actions = nnx_utils.module_jit(model.sample_actions)(
        key,
        obs,
        num_steps=4,
        legato_prev_actions=prev_actions,
        legato_prefix_len=2,
        legato_ramp_end=4,
    )
    assert actions.shape == (batch_size, model.action_horizon, model.action_dim)


